    /// 一首歌与其对应大师语料的稳定绑定（顺序即歌单顺序）
    struct Entry {
        let song: JazzSong
        let resource: String   // 对应 SoloistResourceDirectory 中的 resource 名
    }

    let entries: [Entry]

    init() {
        self.entries = BuiltinForSoloistLibrary.makeEntries()
    }

    var songs: [JazzSong] { entries.map { $0.song } }

    var playlist: JazzPlaylist {
        JazzPlaylist(name: name, songs: songs)
    }

    /// 按 JazzSong 取对应大师 resource（选歌联动用；非本歌单返回 nil）
    func resource(for song: JazzSong) -> String? {
        entries.first { $0.song.id == song.id }?.resource
    }

